const { test, expect } = require('@playwright/test');
test('registration → upload → playback → like → comment', async ({ page }, info) => {
  const h264 = await page.evaluate(() => document.createElement('video').canPlayType('video/mp4; codecs="avc1.42E01E"'));
  if (info.project.name === 'chrome') expect(h264, 'Installed Chrome must support H.264').not.toBe('');
  test.skip(!h264, 'This browser build lacks H.264; playback remains unverified, not passed.');
  const title = `E2E ${info.project.name} ${Date.now()}`;
  await page.goto('/register');
  await page.getByLabel('Как вас зовут').fill('Тестовый автор');
  await page.getByLabel('Email', { exact: true }).fill(`e2e-${Date.now()}-${info.project.name}@example.com`);
  await page.locator('input[autocomplete="new-password"]').fill('E2E-password-only-2026');
  await page.getByRole('button', { name: 'Создать аккаунт', exact: true }).click();
  await expect(page).not.toHaveURL(/register/);
  await page.goto('/upload');
  await page.getByLabel('Видеофайл').setInputFiles(process.env.E2E_MEDIA_FILE || '/media/sample.mp4');
  await page.getByLabel('Название', { exact: false }).fill(title);
  await page.getByRole('button', { name: 'Загрузить видео', exact: true }).click();
  await expect(page.getByText('Готовим ваше видео к просмотру')).toBeVisible();
  await page.getByRole('link', { name: /Перейти в студию/ }).click();
  await page.getByRole('link', { name: `Смотреть ${title}`, exact: true }).click({ timeout: 120000 });
  const video = page.locator('video');
  await expect(video).toBeVisible();
  await video.evaluate(async v => { v.muted = true; await v.play(); });
  await expect.poll(() => video.evaluate(v => v.currentTime)).toBeGreaterThan(0);
  await page.getByRole('button', { name: 'Нравится', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Нравится', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await page.getByLabel('Комментарий', { exact: true }).fill(title);
  await page.getByRole('button', { name: 'Отправить', exact: true }).click();
  await expect(page.locator('.comment').filter({ hasText: title })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('button', { name: 'Нравится', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await expect(page.locator('.comment').filter({ hasText: title })).toBeVisible();
  await page.setViewportSize({ width: 359, height: 800 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
